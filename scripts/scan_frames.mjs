import fs from 'fs';
import path from 'path';

const framesDir = path.resolve('public/frames');
const manifestJsPath = path.resolve('src/home/frameManifest.js');
const manifestJsonPath = path.resolve('public/frames/manifest.json');

if (!fs.existsSync(framesDir)) {
  console.error('Frames directory does not exist:', framesDir);
  process.exit(1);
}

const allFiles = fs.readdirSync(framesDir)
  .filter(f => /\.(jpg|jpeg|png|webp)$/i.test(f))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

if (allFiles.length === 0) {
  console.error('No frame image files found in:', framesDir);
  process.exit(1);
}

const totalFrames = allFiles.length;
const firstFile = allFiles[0];
const lastFile = allFiles[totalFrames - 1];

// Detect naming pattern
// e.g. "ezgif-frame-001.jpg" -> prefix: "ezgif-frame-", digits: 3, ext: "jpg"
const match = firstFile.match(/^(.*?)(\d+)\.([a-zA-Z0-9]+)$/);
let prefix = '';
let digits = 3;
let extension = 'jpg';

if (match) {
  prefix = match[1];
  digits = match[2].length;
  extension = match[3];
}

// Inspect image dimensions from the first frame
function getJpegDimensions(filePath) {
  const buffer = fs.readFileSync(filePath);
  let i = 0;
  if (buffer[0] !== 0xFF || buffer[1] !== 0xD8) {
    return { width: 1280, height: 736 }; // default fallback
  }
  i += 2;
  while (i < buffer.length) {
    if (buffer[i] !== 0xFF) break;
    const marker = buffer[i + 1];
    if (marker === 0xC0 || marker === 0xC2) {
      const height = buffer.readUInt16BE(i + 5);
      const width = buffer.readUInt16BE(i + 7);
      return { width, height };
    }
    const len = buffer.readUInt16BE(i + 2);
    i += 2 + len;
  }
  return { width: 1280, height: 736 };
}

const firstFilePath = path.join(framesDir, firstFile);
const dimensions = getJpegDimensions(firstFilePath);

const manifestData = {
  totalFrames,
  prefix,
  digits,
  extension,
  width: dimensions.width,
  height: dimensions.height,
  aspectRatio: Number((dimensions.width / dimensions.height).toFixed(4)),
  sampleFirst: firstFile,
  sampleLast: lastFile,
  framePattern: `${prefix}%0${digits}d.${extension}`,
  getFrameUrl: `(index, baseUrl = '') => \`\${baseUrl}frames/${prefix}\${String(index).padStart(${digits}, '0')}.${extension}\``
};

// Write src/home/frameManifest.js
const jsContent = `/**
 * Auto-generated by scripts/scan_frames.mjs
 * DO NOT EDIT MANUALLY - Re-run "npm run frames:scan" after updating /public/frames
 */
export const frameManifest = {
  totalFrames: ${totalFrames},
  prefix: ${JSON.stringify(prefix)},
  digits: ${digits},
  extension: ${JSON.stringify(extension)},
  width: ${dimensions.width},
  height: ${dimensions.height},
  aspectRatio: ${manifestData.aspectRatio},
  sampleFirst: ${JSON.stringify(firstFile)},
  sampleLast: ${JSON.stringify(lastFile)},
  getFrameUrl: (index, baseUrl = '') => {
    const padNum = String(index).padStart(${digits}, '0');
    return \`\${baseUrl}frames/${prefix}\${padNum}.${extension}\`;
  }
};

export default frameManifest;
`;

fs.mkdirSync(path.dirname(manifestJsPath), { recursive: true });
fs.writeFileSync(manifestJsPath, jsContent, 'utf-8');
fs.writeFileSync(manifestJsonPath, JSON.stringify(manifestData, null, 2), 'utf-8');

console.log('✅ Frame scan complete:');
console.log(`   - Total Frames: ${totalFrames}`);
console.log(`   - Resolution: ${dimensions.width}x${dimensions.height}`);
console.log(`   - Pattern: ${prefix}{${digits} digits}.${extension}`);
console.log(`   - Output: ${manifestJsPath}`);
console.log(`   - Output: ${manifestJsonPath}`);
